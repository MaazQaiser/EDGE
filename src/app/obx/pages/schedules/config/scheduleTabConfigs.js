/**
 * What the main service tab puts in its left column, and therefore what it draws
 * in the grid.
 *
 * `ROUTES` is the original view: one row per route, cards are the routes. In
 * `COMPANIES` the rows become the customers and the cards become the **visits** —
 * the same week, one level down. A route is a club of visits, so these are two
 * readings of one dataset rather than two datasets, which is why this is a
 * grouping switch on one tab and not a second tab.
 */
export const MAIN_VIEW_GROUPING = {
  ROUTES: 'routes',
  COMPANIES: 'companies',
};

/**
 * Only the tenant whose whole book is visits gets the grouping switch: on a
 * multi-service tenant the main tab is a cross-service roll-up whose rows are
 * already two different kinds of thing, and a company grouping there would have
 * to drop the dedicated half to mean anything.
 */
export const canGroupMainViewByCompany = ({ services = {}, tabConfig } = {}) =>
  Boolean(tabConfig?.isOverviewTab) && isSingleServiceTenant(services) && services?.patrol === true;

/**
 * Whether the things on screen are **visits** rather than shifts.
 *
 * Everything downstream that has to name the unit — the unrouted-demand pill, its
 * tooltip, the footer's status list — was keying off `isVisitsTab`, which is a
 * fact about the tab and not about the cards. The company grouping draws visits
 * from the main tab's config, so on that surface the tab flag says shifts while
 * the grid says visits, and the copy followed the flag.
 */
export const isVisitsSubject = ({ tabConfig, isCompanyGrouping = false } = {}) =>
  Boolean(tabConfig?.isVisitsTab) || Boolean(isCompanyGrouping);

/**
 * The main tab's config as the **company grouping** needs its filter row.
 *
 * `All Jobs` and `Locations` are questions about the routes reading: a job type
 * only distinguishes rows whose subject is a shift, and a location is a level
 * *below* the site — under a company row neither narrows anything the planner can
 * see, so they were two dropdowns that looked like they did something and did not.
 *
 * The technician dropdown goes with them, for a sharper reason: it *would* have
 * narrowed, and narrowed the wrong thing. Grouped by company the row is a customer
 * and the technician is a fact about the individual card, so picking one empties
 * whole company rows — the grid then says "this customer has no work this week"
 * when the truth is "this technician has none at this customer". A control that
 * turns one question into a different one is worse than a missing control.
 *
 * A grouping, not a tab, so this cannot be a flag on `SCHEDULE_TAB_CONFIGS.overview`
 * — the dedicated and patrol tabs and the multi-service overview share that config
 * and still need all three, and the routes grouping keeps the technician dropdown
 * (see `withRouteGroupingFilters`). The caller hands the result to the filter row
 * only; the fetch keeps reading the real config, and drops the same three
 * dimensions from the query so none of them can narrow the payload with no dropdown
 * left to clear it.
 */
export const withCompanyGroupingFilters = (tabConfig) => ({
  ...tabConfig,
  filters: {
    ...tabConfig?.filters,
    showShiftType: false,
    showLocation: false,
    showOfficer: false,
  },
});

/**
 * The main tab's config as the **routes grouping** needs its filter row — the
 * sibling of `withCompanyGroupingFilters`, and it drops two of the same three.
 *
 * `Locations` goes because on this tenant it is a level that does not exist as a
 * question. A route's rows are routes and its cards are visits, and a visit is one
 * service occurrence at one *site*; the location dimension below the site is a
 * dedicated-guarding idea (a post, a patrol point) that the visits book never
 * populates, so the dropdown offered a list the grid could not be narrowed by.
 * Note the week view was its only surface anyway — day and month already hide it,
 * because their fetches drop `locationId` — so this closes the one reading that
 * still showed a control the planner had nothing to do with.
 *
 * `All Jobs` goes for the reason the company grouping drops it, one step stronger:
 * the tenant that gets the grouping switch is single-service by definition
 * (`canGroupMainViewByCompany`), so *every* card on the tab is the same job type and
 * the dropdown's only two meaningful positions are "all" and "all". With the company
 * grouping already dropping it, this makes the job filter absent from **both**
 * readings of that tab — all three views — which is the honest end state: a question
 * with one answer is not a filter.
 *
 * The `showOfficer` dropdown **stays** — the row of installers, in this tenant's
 * words. It is the one of the three that still narrows the right thing here: the
 * rows are routes, a route has one person on it, and picking one selects routes
 * rather than emptying them. Unchanged on week; day and month drop it in the fetch
 * and hide it for the same reason they drop `Locations`.
 *
 * Derived per grouping for the same reason as its sibling — the main tab's config is
 * shared with tabs that ask all three questions — and the fetch drops `shiftType`
 * and `locationId` alongside it, so neither can keep narrowing the payload once its
 * control is gone.
 */
export const withRouteGroupingFilters = (tabConfig) => ({
  ...tabConfig,
  filters: {
    ...tabConfig?.filters,
    showShiftType: false,
    showLocation: false,
  },
});

export const RESOURCE_AREA_HEADER_KEYS = {
  OFFICERS: 'officers',
  LOCATIONS: 'locations',
  RUNSHEETS: 'runsheets',
  SITES: 'sites',
  COMPANIES: 'companies',
};

export const resolveResourceAreaHeader = (headerKey, getLabel, t) => {
  if (!headerKey) return '';

  if (headerKey === RESOURCE_AREA_HEADER_KEYS.OFFICERS) {
    return getLabel?.('terms', 'officers', t) || 'Officers';
  }
  if (headerKey === RESOURCE_AREA_HEADER_KEYS.RUNSHEETS) {
    return getLabel?.('terms', 'runsheets', t) || 'Runsheets';
  }
  if (headerKey === RESOURCE_AREA_HEADER_KEYS.LOCATIONS) {
    return t?.('obx.schedules.calendar.resourceHeaders.locations') || 'Locations';
  }
  if (headerKey === RESOURCE_AREA_HEADER_KEYS.SITES) {
    return getLabel?.('terms', 'sites', t) || 'Sites';
  }
  if (headerKey === RESOURCE_AREA_HEADER_KEYS.COMPANIES) {
    return t?.('obx.schedules.calendar.companies.companyColumn') || 'Company';
  }

  return '';
};

