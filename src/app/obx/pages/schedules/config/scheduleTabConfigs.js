export const getScheduleTabFooterVariant = (tabId) => getScheduleTabConfig(tabId).footerVariant;

/**
 * The footer variant for a tab **as it is currently grouped**.
 *
 * `footerVariant` is a property of the tab config, and the routes grouping shares
 * the main tab's config — so the company grouping inherited the overview footer.
 * That footer counts `Split`, a shift concept permanently 0 for visits, and counts
 * no missed or cancelled visits at all, which is why it summed to 6 of the 8
 * visits the week grid had drawn. Grouped by company the subject is visits, so the
 * visits variant is the honest one; it has to be resolved per grouping because the
 * tab id alone cannot tell the two readings apart.
 */
export const resolveScheduleFooterVariant = (tabId, { isCompanyGrouping = false } = {}) => {
  const tabConfig = getScheduleTabConfig(tabId);

  return isVisitsSubject({ tabConfig, isCompanyGrouping })
    ? SCHEDULE_STATS_FOOTER_VARIANTS.VISITS
    : tabConfig.footerVariant;
};
