const resolveDutyTerm = (key, fallback, { getLabel, t, shiftTypes = {} } = {}) => {
  const fromShiftTypes =
    shiftTypes?.[key]?.label || (typeof shiftTypes?.[key] === 'string' ? shiftTypes[key] : '');
  const fromTerms = getLabel?.('terms', key, t);
  return fromShiftTypes || fromTerms || fallback;
};

/**
 * Remap API day/week section titles (e.g. "Patrol Runsheets") to tenant labels.
 */
export const resolveScheduleSectionTitle = (title, { getLabel, t, shiftTypes = {} } = {}) => {
  if (!title) return title;

  const patrol = resolveDutyTerm('patrol', 'Patrol', { getLabel, t, shiftTypes });
  const dedicated = resolveDutyTerm('dedicated', 'Dedicated', { getLabel, t, shiftTypes });
  const runsheets = getLabel?.('terms', 'runsheets', t) || 'Runsheets';
  const runsheet = getLabel?.('terms', 'runsheet', t) || 'Runsheet';

  const replacements = [
    [/Patrol\s+Runsheets/gi, `${patrol} ${runsheets}`],
    [/Patrol\s+Runsheet/gi, `${patrol} ${runsheet}`],
    [/Patrol\s+Shifts/gi, `${patrol} Shifts`],
    [/Patrol\s+Jobs/gi, `${patrol} Jobs`],
    [/Dedicated\s+Shifts/gi, `${dedicated} Shifts`],
    [/Dedicated\s+Duties/gi, `${dedicated} Duties`],
    [/Dedicated\s+Jobs/gi, `${dedicated} Jobs`],
    [/Dedicated\s+Runsheets/gi, `${dedicated} ${runsheets}`],
  ];

  return replacements.reduce(
    (result, [pattern, replacement]) => result.replace(pattern, replacement),
    String(title),
  );
};

export const getOverviewSections = ({ services = {}, getLabel, t, shiftTypes = {} } = {}) => {
  const resolveTerm = (key, fallback) =>
    resolveDutyTerm(key, fallback, { getLabel, t, shiftTypes });

  const sections = [];

  if (services?.patrol === true) {
    sections.push({
      id: 'overview-patrol',
      type: 'accordion-section',
      title: `${resolveTerm('patrol', 'Patrol')} Shifts`,
      rows: [],
    });
  }

  if (services?.dedicated === true) {
    sections.push({
      id: 'overview-dedicated',
      type: 'accordion-section',
      title: `${resolveTerm('dedicated', 'Dedicated')} Shifts`,
      rows: [],
    });
  }

  return sections;
};

